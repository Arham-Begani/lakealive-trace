// Demo outcomes live outside the inference engine. Planner receives observations only.
import { expectedBand } from './model.js';
import { METHOD } from './scenarios.js';
export function simulatedReading(scenarioId,siteId) {
 const masks={'first-signal':2,'two-signals':5,restricted:2,ambiguous:2,contradiction:0};
 if(!(scenarioId in masks)) throw new Error('Unknown simulator scenario');
 if(scenarioId==='ambiguous') return {low:0,high:.95,method:METHOD,note:'Synthetic coarse-method reading; keep the full interval.',review:false};
 const [l,h]=expectedBand(masks[scenarioId],siteId),v=(l+h)/2;
 return {low:Number(Math.max(0,v-.03).toFixed(3)),high:Number((v+.03).toFixed(3)),method:METHOD,note:'Generated by the fictional scenario. No field measurement.',review:false};
}
